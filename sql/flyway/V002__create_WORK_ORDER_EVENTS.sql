CREATE TABLE IF NOT EXISTS WORK_ORDER_EVENTS (
    EVENT_ID STRING PRIMARY KEY,
    WORK_ORDER_ID STRING NOT NULL,
    CLIENT_ID STRING NOT NULL,
    EVENT_TYPE STRING NOT NULL,
    EVENT_TIMESTAMP_UTC TIMESTAMP_TZ NOT NULL,
    UPDATED_AT_UTC TIMESTAMP_TZ NOT NULL,
    PRIORITY STRING,
    TECHNICIAN_ID STRING,
    STORE_ID STRING,
    REGION STRING,
    LABOR_MINUTES NUMBER(10,0),
    SOURCE_SYSTEM STRING,
    SOURCE_FILE STRING NOT NULL,
    SOURCE_ROW_NUMBER NUMBER NOT NULL,
    PAYLOAD_HASH STRING NOT NULL,
    RAW_PAYLOAD VARIANT,
    FIRST_SEEN_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    LAST_SEEN_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
